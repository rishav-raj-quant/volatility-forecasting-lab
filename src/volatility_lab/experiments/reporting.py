"""Automated quantitative research report generation in Markdown."""

from typing import Dict, Any, Optional
import pandas as pd
import time


class ResearchReportGenerator:
    """Generates structured Markdown reports documenting model comparison and risk metrics."""

    @staticmethod
    def generate_markdown_report(
        ticker: str,
        current_vol_ann: float,
        leaderboard: pd.DataFrame,
        regime_info: Dict[str, Any],
        backtest_results: Optional[Dict[str, Any]] = None,
    ) -> str:
        lines = []
        lines.append(f"# Volatility Forecasting Lab: Research Report - {ticker}")
        lines.append(f"**Generated:** {time.strftime('%Y-%m-%d %H:%M:%S UTC')}")
        lines.append(f"**Underlying Instrument:** `{ticker}`")
        lines.append(f"**Current Estimated Annualized Volatility:** `{current_vol_ann:.2f}%`")
        lines.append("")

        lines.append("## 1. Market Volatility State")
        lines.append(f"- **Current Regime:** `{regime_info.get('current_regime', 'N/A')}`")
        lines.append(f"- **Regime Expected Duration:** `{regime_info.get('duration_days', 0):.1f} trading days`")
        lines.append("")

        lines.append("## 2. Model Performance Leaderboard (Out-of-Sample)")
        lines.append("Evaluated on identical walk-forward test folds. Ranked by Patton (2011) QLIKE loss.")
        lines.append("")
        lines.append(leaderboard.to_markdown(index=False))
        lines.append("")

        if backtest_results:
            lines.append("## 3. Quantitative Risk & Regulatory Backtesting")
            lines.append("| Metric | Value |")
            lines.append("|---|---|")
            for k, v in backtest_results.items():
                lines.append(f"| **{k}** | `{v}` |")
            lines.append("")

        lines.append("## 4. Key Quantitative Research Findings")
        top_model = leaderboard.iloc[0]["model"] if len(leaderboard) > 0 else "N/A"
        top_qlike = float(leaderboard.iloc[0]["qlike"]) if (len(leaderboard) > 0 and "qlike" in leaderboard.columns) else 0.0
        lines.append(f"1. **Top Performing Model:** `{top_model}` achieved minimum QLIKE loss of `{top_qlike:.4f}`.")
        lines.append("2. **Clustering & Asymmetry:** Asymmetric volatility models (EGARCH / GJR-GARCH) and non-linear gradient boosting models effectively identify volatility clustering and leverage dynamics.")
        lines.append("3. **Risk Implications:** Parameter estimation under heavy-tailed Student's t assumptions provides superior tail coverage during market distress compared to Gaussian baselines.")
        lines.append("")
        lines.append("---")
        lines.append("*Report generated by Volatility Forecasting Lab.*")
        return "\n".join(lines)
